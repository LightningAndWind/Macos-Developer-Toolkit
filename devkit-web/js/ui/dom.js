export function icon(name, size = 16, cls = '') {
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('width', String(size));
  svg.setAttribute('height', String(size));
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-width', '1.7');
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('class', `icon ${cls}`.trim());
  if (name === 'github') {
    // GitHub 标记是实心路径，不能沿用描边参数
    svg.setAttribute('fill', 'currentColor');
    svg.setAttribute('stroke', 'none');
    svg.setAttribute('stroke-width', '0');
  }
  svg.innerHTML = ICONS[name] ?? ICONS.info;
  return svg;
}

/**
 * 轻量 hyperscript。
 * h('div', {class:'x', onclick: fn, dataset:{id:'1'}}, child, child…)
 */
export function h(tag, props = null, ...children) {
  const el = document.createElement(tag);
  if (props) {
    for (const [key, value] of Object.entries(props)) {
      if (value === undefined || value === null || value === false) continue;
      if (key === 'class' || key === 'className') {
        el.className = value;
      } else if (key === 'dataset') {
        Object.assign(el.dataset, value);
      } else if (key === 'style') {
        if (typeof value === 'string') {
          el.style.cssText = value;
        } else {
          for (const [prop, propValue] of Object.entries(value)) {
            if (propValue === null || propValue === undefined) continue;
            if (prop.startsWith('--')) el.style.setProperty(prop, String(propValue));
            else el.style[prop] = propValue;
          }
        }
      } else if (key === 'html') {
        el.innerHTML = value;
      } else if (key.startsWith('on') && typeof value === 'function') {
        el.addEventListener(key.slice(2).toLowerCase(), value);
      } else if (key === 'value') {
        el.value = value;
      } else if (key === 'checked') {
        el.checked = Boolean(value);
      } else if (key === 'disabled') {
        el.disabled = Boolean(value);
      } else if (key === 'ref' && typeof value === 'function') {
        value(el);
      } else {
        el.setAttribute(key, value === true ? '' : String(value));
      }
    }
  }
  append(el, children);
  return el;
}

function append(el, children) {
  for (const child of children.flat(Infinity)) {
    if (child === null || child === undefined || child === false || child === '') continue;
    el.append(child instanceof Node ? child : document.createTextNode(String(child)));
  }
}

export function frag(...children) {
  const f = document.createDocumentFragment();
  append(f, children);
  return f;
}

