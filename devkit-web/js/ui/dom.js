export function formatBytes(bytes) {
  if (!Number.isFinite(bytes) || bytes <= 0) return '0 B';
  if (bytes < 1000) return `${bytes} B`;
  if (bytes < 1_000_000) return `${(bytes / 1000).toFixed(bytes < 10_000 ? 1 : 0)} KB`;
  if (bytes < 1_000_000_000) return `${(bytes / 1_000_000).toFixed(1)} MB`;
  return `${(bytes / 1_000_000_000).toFixed(2)} GB`;
}

export function formatDuration(ms) {
  if (ms < 1000) return `${Math.round(ms)} ms`;
  return `${(ms / 1000).toFixed(2)} s`;
}

export function formatTimeout(seconds) {
  const clamped = Math.min(3600, Math.max(1, Number(seconds) || 30));
  if (clamped % 3600 === 0) return `${clamped / 3600}h`;
  if (clamped % 60 === 0) return `${clamped / 60}m`;
  return `${clamped}s`;
}

const pad = (n) => String(n).padStart(2, '0');

export function historyTime(ts) {
  const d = new Date(ts);
  const now = new Date();
  const hm = `${pad(d.getHours())}:${pad(d.getMinutes())}`;
  if (d.toDateString() === now.toDateString()) return hm;
  if (d.getFullYear() === now.getFullYear()) return `${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${hm}`;
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${hm}`;
}

export function fullTime(ts) {
  const d = new Date(ts);
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())} ${pad(d.getHours())}:${pad(
    d.getMinutes()
  )}:${pad(d.getSeconds())}`;
}

export function methodColor(method) {
  switch (String(method).toUpperCase()) {
    case 'GET': return 'var(--green)';
    case 'POST': return 'var(--blue)';
    case 'PUT':
    case 'PATCH': return 'var(--orange)';
    case 'DELETE': return 'var(--red)';
    case 'HEAD': return 'var(--purple)';
    case 'OPTIONS': return 'var(--teal)';
    default: return 'var(--text-2)';
  }
}

export function statusInfo(code) {
  if (!code) return { color: 'var(--text-3)', label: '网络错误' };
  if (code < 200) return { color: 'var(--text-2)', label: '信息' };
  if (code < 300) return { color: 'var(--green)', label: '成功' };
  if (code < 400) return { color: 'var(--blue)', label: '重定向' };
  if (code < 500) return { color: 'var(--orange)', label: '客户端错误' };
  if (code < 600) return { color: 'var(--red)', label: '服务器错误' };
  return { color: 'var(--text-2)', label: '未知' };
}

export async function copyText(text) {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    const ta = document.createElement('textarea');
    ta.value = text;
    ta.style.position = 'fixed';
    ta.style.opacity = '0';
    document.body.append(ta);
    ta.select();
    const ok = document.execCommand('copy');
    ta.remove();
    return ok;
  }
}

export function downloadFile(filename, content, mime = 'application/json') {
  const blob = content instanceof Blob ? content : new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.append(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 4000);
}

